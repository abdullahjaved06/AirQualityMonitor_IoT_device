/* Character lookup */
static inline int pixel_font_index(char c) {
    switch(c) {
        case ' ': return 0;
        case '(': return 1;
        case ')': return 2;
        case '%': return 3;
        case '0': return 4;
        case '1': return 5;
        case '2': return 6;
        case 'C': return 7;
        case 'E': return 8;
        case 'H': return 9;
        case 'M': return 10;
        case 'O': return 11;
        case 'P': return 12;
        case 'T': return 13;
        case 'U': return 14;
        case 'm': return 15;
        case 'p': return 16;
        default: return 0;  /* space for unknown */
    }
}

